-- aARgon3 2.3: behavior points for staff, and custom-order requests from the website.
-- Run once in the aARgon3 & Mexel Backend project's SQL Editor, after aargon3-2.1.sql. Safe to run again.

-- ============================================================ points
-- Managers give or take points for behavior (great service, covering a shift, late, no-show...).
-- Nothing is ever edited: a mistake is undone, and the undo is kept in the history.
create table if not exists public.points (
  id bigint generated by default as identity primary key,
  user_id uuid not null,                  -- who the points are for (staff.user_id)
  points integer not null check (points between -50 and 50 and points <> 0),
  reason text not null check (length(trim(reason)) between 2 and 200),
  kind text not null default 'manual' check (kind in ('manual', 'late', 'auto')),
  given_by text, given_by_id uuid,
  undone_at timestamptz, undone_by text,
  created_at timestamptz not null default now()
);
create index if not exists points_user_idx on public.points (user_id, created_at desc);
alter table public.points enable row level security;
revoke all on public.points from anon, authenticated;

insert into public.settings (key, value) values ('points', '{"late": 0}'::jsonb) on conflict (key) do nothing;

create or replace function public.a3_point_json(x public.points) returns jsonb language sql stable as $$
  select jsonb_build_object('id', x.id, 'user_id', x.user_id, 'points', x.points, 'reason', x.reason, 'kind', x.kind,
    'given_by', x.given_by, 'given_by_id', x.given_by_id, 'undone', x.undone_at is not null, 'undone_at', x.undone_at, 'undone_by', x.undone_by,
    'created_at', x.created_at,
    'name', (select coalesce(s.display_name, s.name, s.email) from staff s where s.user_id = x.user_id))
$$;

create or replace function public.a3_points_give(p_user uuid, p_points integer, p_reason text, p_kind text, p_by text, p_by_id uuid) returns jsonb
language plpgsql security definer set search_path = public as $$
declare x public.points;
begin
  if not exists (select 1 from staff where user_id = p_user and active) then raise exception 'That person isn''t on the team.'; end if;
  if p_points is null or p_points = 0 or abs(p_points) > 50 then raise exception 'Points go from -50 to 50 (not 0).'; end if;
  if length(trim(coalesce(p_reason, ''))) < 2 then raise exception 'Say what the points are for.'; end if;
  insert into points (user_id, points, reason, kind, given_by, given_by_id)
  values (p_user, p_points, left(trim(p_reason), 200), coalesce(p_kind, 'manual'), p_by, p_by_id) returning * into x;
  return public.a3_point_json(x);
end $$;

create or replace function public.a3_points_undo(p_id bigint, p_by text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare x public.points;
begin
  update points set undone_at = now(), undone_by = p_by where id = p_id and undone_at is null returning * into x;
  if x.id is null then raise exception 'Already undone, or not found.'; end if;
  return public.a3_point_json(x);
end $$;

-- history: one person (p_user) or everyone (null)
create or replace function public.a3_points(p_user uuid, p_limit integer) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(public.a3_point_json(x) order by x.created_at desc), '[]'::jsonb)
  from (select * from points where p_user is null or user_id = p_user order by created_at desc limit least(greatest(coalesce(p_limit, 100), 1), 1000)) x
$$;

-- totals for everyone active: all time, this month (from p_month_start), last 30 days
create or replace function public.a3_points_board(p_month_start timestamptz) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(r order by (r->>'total')::int desc, r->>'name'), '[]'::jsonb) from (
    select jsonb_build_object('user_id', s.user_id, 'name', coalesce(s.display_name, s.name, s.email), 'role', s.role, 'color', s.color, 'title', s.title,
      'total', coalesce(sum(p.points), 0),
      'month', coalesce(sum(p.points) filter (where p.created_at >= p_month_start), 0),
      'given', coalesce(sum(p.points) filter (where p.points > 0), 0),
      'taken', coalesce(sum(p.points) filter (where p.points < 0), 0),
      'last', max(p.created_at)) r
    from staff s left join points p on p.user_id = s.user_id and p.undone_at is null
    where s.active and s.user_id is not null
    group by s.user_id, s.display_name, s.name, s.email, s.role, s.color, s.title
  ) t
$$;

-- the owner's points setting ("late clock-in costs N points") joins the allowed settings
create or replace function public.a3_setting_set(p_key text, p_value jsonb, p_by text) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  if p_key not in ('store', 'business', 'goals', 'points') then raise exception 'Unknown setting.'; end if;
  insert into settings (key, value, updated_by, updated_at) values (p_key, p_value, p_by, now())
  on conflict (key) do update set value = excluded.value, updated_by = excluded.updated_by, updated_at = now();
  return public.a3_settings();
end $$;

-- ============================================================ custom-order requests from the website
-- A customer builds what they want on the store's "Custom" tab; it lands in the terminal's Custom orders as
-- "Requested" for staff to price and send (link, invoice or free). No payment happens until staff send it.
alter table public.quotes drop constraint if exists quotes_status_check;
alter table public.quotes add constraint quotes_status_check check (status in ('requested', 'draft', 'sent', 'paid', 'cancelled'));
alter table public.quotes add column if not exists source text not null default 'staff';
alter table public.quotes add column if not exists request jsonb;   -- what the customer asked for, kept as they sent it

create or replace function public.a3_quote_request(p jsonb) returns jsonb
language plpgsql security definer set search_path = public as $$
declare q public.quotes; em text := lower(trim(p->'customer'->>'email'));
begin
  if em is null or em !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then raise exception 'Enter a valid email.'; end if;
  -- keep the inbox sane: 3 open requests per email a day, 40 an hour for the whole site
  if (select count(*) from quotes where source = 'web' and lower(customer->>'email') = em and created_at > now() - interval '1 day') >= 3 then
    raise exception 'We already have your requests. We''ll be in touch soon.'; end if;
  if (select count(*) from quotes where source = 'web' and created_at > now() - interval '1 hour') >= 40 then
    raise exception 'Lots of requests right now. Please try again in a bit.'; end if;
  insert into quotes (quote_no, status, source, plan, tier, seats, interval, amount_cents, config, items, customer, notes, request, valid_until, created_by)
  values (p->>'quote_no', 'requested', 'web', p->>'plan', p->>'tier', (p->>'seats')::int, coalesce(p->>'interval', 'month'), 0,
          coalesce(p->'config', '{}'), coalesce(p->'items', '[]'), p->'customer', p->>'notes', p->'request', current_date + 30, 'Website')
  returning * into q;
  return jsonb_build_object('quote_no', q.quote_no);
end $$;

-- (a3_quote_json from 2.1 is to_jsonb(q), so source and request show up on their own)

-- ============================================================ only the Edge Functions (service key) may call these
do $$
declare f text;
begin
  foreach f in array array['a3_points_give(uuid, integer, text, text, text, uuid)', 'a3_points_undo(bigint, text)', 'a3_points(uuid, integer)',
    'a3_points_board(timestamptz)', 'a3_quote_request(jsonb)', 'a3_setting_set(text, jsonb, text)']
  loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
    execute format('grant execute on function public.%s to service_role', f);
  end loop;
end $$;
